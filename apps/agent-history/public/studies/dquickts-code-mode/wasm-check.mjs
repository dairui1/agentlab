import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(process.argv[2] || '/private/tmp/dquickts-wasm-baseline-20261023');
const home = mkdtempSync(join(tmpdir(), 'wasm-home-'));
process.env = { PATH: process.env.PATH, HOME: home, TMPDIR: home, LANG: 'C', TZ: 'UTC' };
const require = createRequire(join(root, 'package.json'));
const { getQuickJS, newQuickJSAsyncWASMModule } = require('quickjs-emscripten');
const version = require('quickjs-emscripten/package.json').version;
assert.equal(version, '0.32.0');
const checks = [];
const qjs = await getQuickJS();
const vm = qjs.newContext();
function evaluate(code) {
  const value = vm.unwrapResult(vm.evalCode(code));
  const result = vm.dump(value);
  value.dispose();
  return result;
}
assert.equal(evaluate('globalThis.next=(()=>{let n=0;return ()=>++n})(); next()'), 1);
assert.equal(evaluate('next()'), 2);
checks.push({ name: 'state-survives-in-live-context', passed: true, output: 2 });
assert.equal(evaluate('[typeof process, typeof require, typeof fetch].join("|")'), 'undefined|undefined|undefined');
checks.push({ name: 'no-node-or-network-globals-by-default', passed: true });
let deferred;
const tool = vm.newFunction('tool', () => { deferred = vm.newPromise(); return deferred.handle; });
vm.setProp(vm.global, 'tool', tool);
tool.dispose();
const pending = vm.unwrapResult(vm.evalCode('(async()=>{ const x=await tool(); return x+1; })()'));
const resolved = vm.resolvePromise(pending);
const answer = vm.newNumber(41);
deferred.resolve(answer);
answer.dispose();
vm.runtime.executePendingJobs().unwrap();
const result = vm.unwrapResult(await resolved);
assert.equal(vm.getNumber(result), 42);
result.dispose();
pending.dispose();
deferred.dispose();
checks.push({ name: 'async-host-tool-with-promise-job-pump', passed: true, output: 42 });
let polls = 0;
vm.runtime.setInterruptHandler(() => ++polls > 5);
const interrupted = vm.evalCode('while(true){}');
assert.ok(interrupted.error);
const error = vm.dump(interrupted.error);
assert.match(error.message, /interrupted/);
interrupted.error.dispose();
checks.push({ name: 'infinite-loop-interrupt', passed: true, polls, error });
vm.dispose();
const asyncModule = await newQuickJSAsyncWASMModule();
const asyncVm = asyncModule.newContext();
const asyncTool = asyncVm.newAsyncifiedFunction('tool', async () => {
  await Promise.resolve();
  return asyncVm.newNumber(41);
});
asyncVm.setProp(asyncVm.global, 'tool', asyncTool);
asyncTool.dispose();
const asyncResult = asyncVm.unwrapResult(await asyncVm.evalCodeAsync('tool()+1'));
assert.equal(asyncVm.getNumber(asyncResult), 42);
asyncResult.dispose();
asyncVm.dispose();
checks.push({ name: 'asyncify-sync-looking-call-resumes-in-same-process', passed: true, output: 42 });
const report = { generatedAt: new Date().toISOString(), package: 'quickjs-emscripten', version, lockfile: JSON.parse(readFileSync(join(root, 'package-lock.json'), 'utf8')), checks, boundary: 'Asyncify tested only in one live process. No serialize/restore API or cross-process continuation was tested or claimed.' };
writeFileSync(join(here, 'wasm-results.json'), JSON.stringify(report, null, 2) + '\n');
console.log(JSON.stringify({ version, checks }, null, 2));
